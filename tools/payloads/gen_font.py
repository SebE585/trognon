"""Generate font.h: a 5x7 bitmap font, uppercase + digits + punctuation (lowercase maps to uppercase).

Each glyph is 7 rows of 5 characters ('#' = pixel). Output: u8 font5x7[128][7],
one row per byte, bit 4 = leftmost pixel; unknown characters are blank.

Usage: python3 gen_font.py font.h
"""
