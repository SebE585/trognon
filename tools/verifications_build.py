#!/usr/bin/env python3
"""Build and check the Verifications page from tools/verifications.yaml.

    python3 -I tools/verifications_build.py            # write docs/en/verifications.md
    python3 -I tools/verifications_build.py --check    # validate, and fail if the generated page is stale

A verification is an independent check of a published run: someone rebuilt a payload and compared its hash with the bundle's manifest
(`tools/rebuild_bundle.py` prints the row), or audited a claim against its bundle. A mismatch or a failure to reproduce is a result, not
an error. The checks refuse a row for a bundle that does not exist, an unknown result, a match with no commit that exists in the
history, and a negative result with no explanation. `by: maintainer` marks the project's own runs; any other handle is independent.
"""
import argparse
import datetime
import json
import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "verifications.yaml"
OUT = ROOT / "docs" / "en" / "verifications.md"
EVIDENCE = ROOT / "evidence"
KINDS = {"rebuild": ("match", "mismatch", "not-reproducible"), "claim-audit": ("match", "mismatch", "inconclusive")}
REPO = "https://github.com/SebE585/trognon"
GENERATED = "<!-- generated by tools/verifications_build.py from tools/verifications.yaml: do not edit -->\n"


def commit_exists(c):
    return subprocess.run(["git", "cat-file", "-e", str(c) + "^{commit}"], capture_output=True, cwd=ROOT).returncode == 0


def is_shallow():
    """A shallow clone has no history to look commits up in; CI checks out the full history so the check stays strict there."""
    return subprocess.run(["git", "rev-parse", "--is-shallow-repository"], capture_output=True, text=True, cwd=ROOT).stdout.strip() == "true"


def bundles():
    return sorted(p.name for p in EVIDENCE.iterdir() if (p / "manifest.json").is_file())


def check(rows, exists=None, commit_ok=commit_exists):
    exists = exists or (lambda b: (EVIDENCE / b / "manifest.json").is_file())
    errors = []
    for i, r in enumerate(rows):
        where = "%s (row %d)" % (r.get("bundle"), i + 1)
        if not exists(r.get("bundle", "")):
            errors.append("%s: not a bundle under evidence/" % where)
        kind = r.get("kind")
        if kind not in KINDS:
            errors.append("%s: unknown kind %r" % (where, kind))
            continue
        if r.get("result") not in KINDS[kind]:
            errors.append("%s: result %r is not one of %s for a %s" % (where, r.get("result"), ", ".join(KINDS[kind]), kind))
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(r.get("date", ""))):
            errors.append("%s: needs an ISO date" % where)
        if not r.get("by") or r.get("by") == "YOUR-GITHUB-HANDLE":
            errors.append("%s: needs 'by', your GitHub handle" % where)
        if kind == "rebuild":
            env = r.get("environment") or {}
            if not env.get("host") or not env.get("toolchain"):
                errors.append("%s: a rebuild records its host and toolchain" % where)
            if r.get("result") in ("match", "mismatch"):
                if not r.get("commit"):
                    errors.append("%s: a %s names the commit that was built" % (where, r.get("result")))
                elif not commit_ok(r["commit"]):
                    errors.append("%s: commit %s is not in the repository history" % (where, r["commit"]))
        if kind == "claim-audit" and not (r.get("claim") and r.get("page")):
            errors.append("%s: a claim audit quotes the claim and names its page" % where)
        if r.get("result") in ("mismatch", "not-reproducible", "inconclusive") and not r.get("notes"):
            errors.append("%s: a %s result needs an explanation in 'notes'" % (where, r.get("result")))
    return errors


def independent(r):
    return r.get("by") != "maintainer"


def stats(rows, all_bundles, recorded_commit):
    rebuilt = {r["bundle"] for r in rows if r["kind"] == "rebuild" and r["result"] == "match"}
    ind = {r["bundle"] for r in rows if independent(r)}
    later = {r["bundle"] for r in rows if r["kind"] == "rebuild" and r["result"] == "match" and r.get("commit") and r["commit"] != recorded_commit.get(r["bundle"])}
    return {"bundles": len(all_bundles), "rebuilt": len(rebuilt), "independent": len(ind), "later": len(later),
            "failed": len({r["bundle"] for r in rows if r["result"] == "not-reproducible"}),
            "mismatch": len({r["bundle"] for r in rows if r["result"] == "mismatch"})}


def recorded():
    out = {}
    for b in bundles():
        out[b] = json.loads((EVIDENCE / b / "manifest.json").read_text())["git"]["commit"]
    return out


def row_md(r):
    env = r.get("environment") or {}
    where = ("%s, %s" % (env.get("host", ""), env.get("toolchain", ""))).strip(", ") or "-"
    return "| [`%s`](%s/tree/main/evidence/%s) | %s | %s | `%s` | %s | %s | %s |" % (
        r["bundle"], REPO, r["bundle"], r["kind"], r["result"], (r.get("commit") or "-")[:10], where, r["by"], (r.get("notes") or r.get("claim") or "").replace("|", "\\|"))


def render(rows, all_bundles, recorded_commit):
    s = stats(rows, all_bundles, recorded_commit)
    head = "| Bundle | Check | Result | Commit | Where | By | Notes |\n|---|---|---|---|---|---|---|"
    ind = [r for r in rows if independent(r)]
    own = [r for r in rows if not independent(r)]
    lines = ["---", "title: Verifications", "source: tools/verifications.yaml", "hide:", "  - toc", "---", "", GENERATED, "# Verifications", "",
             "A published run is only as good as someone else's ability to check it. This page records **independent checks of the evidence bundles**: "
             "someone rebuilds a payload and compares its hash with the bundle's manifest, or audits a claim against its bundle. "
             "A mismatch, or a bundle that cannot be reproduced, is a result and is recorded as such.", "",
             "## State", "",
             "- **%d** bundles in [`evidence/`](%s/tree/main/evidence)." % (s["bundles"], REPO),
             "- **%d** have been rebuilt to the exact hash of their manifest (by the maintainer, on one toolchain)." % s["rebuilt"],
             "- **%d** of those rebuild only at a **later commit** than the one recorded, because they were produced from an uncommitted source tree; "
             "new runs now save that tree as `source.diff`. **%d** cannot be rebuilt at all: the first run of a stage whose source changed afterwards." % (s["later"], s["failed"]),
             "- **%d** bundles have been checked by someone other than the maintainer. **%d** mismatches recorded so far." % (s["independent"], s["mismatch"]), "",
             "## Check a bundle yourself", "",
             "You need the repository with its history, `arm-none-eabi-gcc` and `make`; no phone.", "",
             "```sh", "python3 tools/rebuild_bundle.py evidence/<bundle> --search-later --by YOUR-GITHUB-HANDLE", "```", "",
             "It prints one row. Add it to `tools/verifications.yaml` in a pull request (the template asks what you checked and with which toolchain). "
             "A different compiler can produce different bytes: if yours does, that is exactly the result to submit. "
             "See [Missions](missions.md) for this as a first contribution.", ""]
    if ind:
        lines += ["## Independent checks", "", head] + [row_md(r) for r in ind] + [""]
    else:
        lines += ["## Independent checks", "", "None yet. This is the first thing anyone can add.", ""]
    lines += ["## The maintainer's own runs", "", '<details markdown="1">', "<summary>%d rows, on %s</summary>" % (len(own), "one toolchain"), "", head] + [row_md(r) for r in own] + ["", "</details>", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    rows = (yaml.safe_load(SRC.read_text()) or {}).get("verifications") or []
    shallow = is_shallow()
    if shallow:
        print("note: shallow clone, so the existence of the commits cited in the rows is not checked (CI checks it on the full history)")
    errors = check(rows, commit_ok=(lambda c: True) if shallow else commit_exists)
    if errors:
        for e in errors:
            print(e)
        return 1
    text = render(rows, bundles(), recorded())
    yaml.safe_load(re.match(r"^---\n(.*?)\n---\n", text, re.S).group(1))
    if args.check:
        if not OUT.is_file() or OUT.read_text() != text:
            print("%s is missing or stale (run make verifications)" % OUT.relative_to(ROOT))
            return 1
        print("verifications: %d rows valid, generated page up to date" % len(rows))
        return 0
    OUT.write_text(text)
    print("%d rows written to %s" % (len(rows), OUT.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
