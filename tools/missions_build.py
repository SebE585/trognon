#!/usr/bin/env python3
"""Build and check the Missions page from tools/iop_analysis/missions.yaml and the decompilation catalog.

    python3 -I tools/missions_build.py            # write docs/en/missions.md
    python3 -I tools/missions_build.py --check    # validate, and fail if the generated page is stale

A mission is an open question of the catalog framed so that someone else can take it. The question text and the link to its
entry come from the catalog, so they cannot drift; the checks refuse a mission whose question does not exist, a closed mission
with no outcome, a blocked one with no reason, a write-level mission that is offered as open, and a mission that is still open
although the catalog has resolved its question.
"""
import argparse
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import journey_build as jb  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "iop_analysis" / "missions.yaml"
OUT = ROOT / "docs" / "en" / "missions.md"
REPO = "https://github.com/SebE585/trognon"
WORK = {"static": (1, "Level 1 · static analysis"), "survey": (2, "Level 2 · a run that only reads"),
        "write": (3, "Level 3 · hardware writes, maintainer only")}
STATES = ("open", "in-progress", "blocked", "closed")
OUTCOMES = ("confirmed", "refuted", "inconclusive")
STATE_LABEL = {"open": "Open", "in-progress": "In progress", "blocked": "Blocked", "closed": "Closed"}
GENERATED = "<!-- generated by tools/missions_build.py from tools/iop_analysis/missions.yaml: do not edit -->\n"


def questions():
    """({id: dict} of open questions, {ids resolved}) over the approved catalog entries."""
    open_q, resolved = {}, set()
    for binary, fiches in jb.catalog_entries().items():
        for y in fiches:
            for q in (y.get("review") or {}).get("unresolved") or []:
                open_q[q["id"]] = {"text": q.get("text", ""), "proof": q.get("proof_needed", ""), "binary": binary,
                                   "file": y["_file"], "title": jb.fiche_title(y)}
            for r in (y.get("review") or {}).get("resolved") or []:
                resolved.add(r["id"])
    return open_q, resolved


def load():
    return yaml.safe_load(SRC.read_text())["missions"]


def check(missions, open_q, resolved):
    errors, seen = [], set()
    for m in missions:
        q = m.get("question")
        if q in seen:
            errors.append("%s: listed twice" % q)
        seen.add(q)
        if q not in open_q and q not in resolved:
            errors.append("%s: not a question of an approved catalog entry" % q)
        if q in resolved and m.get("state") != "closed":
            errors.append("%s: the catalog has resolved this question, so the mission must be closed" % q)
        if m.get("work") not in WORK:
            errors.append("%s: unknown kind of work %r" % (q, m.get("work")))
        if m.get("state") not in STATES:
            errors.append("%s: unknown state %r" % (q, m.get("state")))
        for field in ("title", "expected"):
            if not m.get(field):
                errors.append("%s: needs %r" % (q, field))
        if m.get("work") in ("static", "survey") and not m.get("needs"):
            errors.append("%s: needs a list of what is required to take it" % q)
        if m.get("work") in ("survey", "write") and not m.get("preconditions"):
            errors.append("%s: a mission that runs on a phone must list its preconditions" % q)
        if not m.get("unlocks"):
            errors.append("%s: needs 'unlocks', what answering would make possible" % q)
        if not m.get("skills"):
            errors.append("%s: needs 'skills', what it takes" % q)
        for c in m.get("contributions") or []:
            if not (c.get("title") and str(c.get("url", "")).startswith("https://github.com/")):
                errors.append("%s: a contribution needs a title and a GitHub URL" % q)
        if m.get("state") == "closed" and not str(m.get("integrated_in", "")).startswith("https://github.com/"):
            errors.append("%s: a closed mission must link the merged contribution (integrated_in)" % q)
        if m.get("state") != "closed" and m.get("integrated_in"):
            errors.append("%s: only a closed mission has integrated_in" % q)
        if m.get("state") == "blocked" and not (m.get("blocked_by") or m.get("blocked_until")):
            errors.append("%s: a blocked mission must say what blocks it" % q)
        for dep in m.get("blocked_until", []):
            if dep not in open_q and dep not in resolved:
                errors.append("%s: blocked until %r, which is not a question of the catalog" % (q, dep))
        if m.get("state") == "blocked" and m.get("blocked_until") and not m.get("blocked_by") \
                and all(d in resolved for d in m["blocked_until"]):
            errors.append("%s: every question it waited for is resolved in the catalog, so it can be opened" % q)
        if m.get("state") == "closed" and m.get("outcome") not in OUTCOMES:
            errors.append("%s: a closed mission needs an outcome (%s)" % (q, ", ".join(OUTCOMES)))
        if m.get("state") != "closed" and m.get("outcome"):
            errors.append("%s: only a closed mission has an outcome" % q)
        if m.get("work") == "write" and m.get("state") == "open":
            errors.append("%s: a hardware-write mission is never offered as open" % q)
    return errors


def issue_url(q):
    return "%s/issues/new?template=mission.yml&title=%s&mission=%s" % (REPO, ("Mission: " + q).replace(" ", "+").replace(":", "%3A"), q)


def card(m, qinfo):
    lvl, label = WORK[m["work"]]
    out = ["- **%s**" % m["title"], ""]
    out.append('    <span class="mission-level mission-level-%d">%s</span> <span class="mission-state mission-state-%s">%s</span>'
               % (lvl, label, m["state"], STATE_LABEL[m["state"]]))
    out.append("")
    if m.get("outcome"):
        out += ["    **Outcome:** %s" % m["outcome"], ""]
    if qinfo:
        out += ["    *The open question* (`%s`): %s" % (m["question"], jb.first_sentence(qinfo["text"], 300)), ""]
    out += ["    **What it would unlock**: %s" % m["unlocks"], ""]
    out += ["    **What you need**", ""] + ["    - %s" % n for n in m.get("needs", [])] + [""]
    out += ["    **Skills**: %s" % ", ".join(m["skills"]), ""]
    if m.get("preconditions"):
        out += ["    **Before you run anything** (these stay in force once the mission is open)", ""] + ["    - %s" % c for c in m["preconditions"]] + [""]
    out += ["    **A good answer**: %s" % m["expected"], ""]
    contrib = m.get("contributions") or []
    out += ["    **Contributions so far**: " + (" · ".join("[%s](%s)" % (c["title"], c["url"]) for c in contrib) if contrib else "none yet"), ""]
    if m.get("integrated_in"):
        out += ["    **Integrated in**: [%s](%s)" % (m["integrated_in"].rsplit("/", 2)[-2] + " " + m["integrated_in"].rsplit("/", 1)[-1], m["integrated_in"]), ""]
    if m.get("blocked_by") or m.get("blocked_until"):
        why = list(m.get("blocked_by", []))
        if m.get("blocked_until"):
            why.append("Waits for the catalog to resolve: %s." % ", ".join("`%s`" % d for d in m["blocked_until"]))
        out += ["    **Blocked by**: " + " ".join(why), ""]
    links = []
    if qinfo:
        links.append("[Catalog entry](%s/blob/main/tools/iop_analysis/catalog/%s/%s)" % (REPO, qinfo["binary"], qinfo["file"]))
    if m["state"] == "open":
        links.append("[Take this mission](%s)" % issue_url(m["question"]))
    out += ["    " + " · ".join(links), ""]
    return out


def render(missions, open_q):
    counts = {s: sum(1 for m in missions if m["state"] == s) for s in STATES}
    taken = {m["question"] for m in missions}
    unclassified = len([q for q in open_q if q not in taken])
    lines = ["---", "title: Missions", "hide:", "  - toc", "---", "", GENERATED,
             "# Missions", "",
             "A mission is an open question of the [decompilation catalog](journey/grimoire.md), framed so that you can take it: what you need, "
             "what a good answer looks like, and what state the work is in. The state of the **work** is not the state of the **knowledge**: "
             "a mission can close because a hypothesis was refuted, and a documented negative result counts as much as a discovery.", "",
             "## How it works", "",
             "1. Pick a mission below and open its *Take this mission* form, so nobody works on it twice by accident.",
             "2. Do the work. Level 1 needs no phone. Level 2 is a run on a phone with a payload that **only reads**: that describes the action, "
             "not a guarantee, because a read can have hardware effects, so each level 2 mission lists preconditions that stay in force. "
             "Level 3, which writes to the phone's hardware, is never open to contributors: it only happens after a written description and the maintainer's agreement.",
             "3. Send what you found as a pull request, with the template's checklist: what you looked for, with which sources and versions, "
             "what you observed, what you conclude and what stays uncertain. No Apple firmware, keys or extracted binaries in a contribution.",
             "4. A review decides what the catalog says. A result is recorded with its method and limits, whichever way it points.", "",
             "See also [CONTRIBUTING](%s/blob/main/CONTRIBUTING.md)." % REPO, "",
             "## What the states mean", "",
             "**Open**: nobody is on it yet. **In progress**: someone has taken it. **Blocked**: it waits for something named on its card. "
             "**Closed**: the expected work is done, reviewed and merged, and the merged contribution is linked. "
             "A mission closes because the work is finished, not because a hypothesis was confirmed: its scientific outcome (confirmed, refuted or inconclusive) is shown separately.", "",
             "## State of the missions", "",
             "%d open · %d in progress · %d blocked · %d closed. **%d other open questions of the catalog are not framed as missions yet** "
             "(see the [map of what we know](journey/grimoire.md))." % (counts["open"], counts["in-progress"], counts["blocked"], counts["closed"], unclassified), ""]
    for state, title in (("open", "Open missions"), ("in-progress", "In progress"), ("blocked", "Blocked"), ("closed", "Closed")):
        group = [m for m in missions if m["state"] == state]
        if not group:
            continue
        lines += ["## " + title, "", '<div class="grid cards stack" markdown>', ""]
        for m in group:
            lines += card(m, open_q.get(m["question"]))
        lines += ["</div>", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="validate and compare with the file on disk, write nothing")
    args = ap.parse_args(argv)
    open_q, resolved = questions()
    missions = load()
    errors = check(missions, open_q, resolved)
    if errors:
        for e in errors:
            print(e)
        return 1
    text = render(missions, open_q)
    front = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    yaml.safe_load(front.group(1))  # the front matter must be valid YAML
    if args.check:
        if not OUT.is_file() or OUT.read_text() != text:
            print("%s is missing or stale (run make missions)" % OUT.relative_to(ROOT))
            return 1
        print("missions: valid, generated page up to date")
        return 0
    OUT.write_text(text)
    print("%d missions written to %s" % (len(missions), OUT.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
