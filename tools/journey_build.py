def annot(cls, label):
    """A small margin label (Read, Hypothesis, Open question, Correction)."""
    return '<span class="journey-annot journey-annot-%s">%s</span>' % (cls, label)


def notebook_block(n, lang):
    ids = n.get("notebook") or []
    corrections = n.get("corrections") or []
    if not ids and not corrections:
        return ""
    count = len(ids) + len(corrections)
    out = ['<details class="journey-notebook" markdown="1" data-label="%s" data-back="%s">' % (T(lang, "nb_panel"), T(lang, "nb_back")),
           "<summary>%s</summary>" % (T(lang, "nb_summary") % (count, plural(count))), ""]
    for k, i in enumerate(ids, 1):
        it = ITEMS[i]
        note = ""
        if it["kind"] == "question":
            mark = annot("open", T(lang, "annot_open"))
        elif it["status"] == "hypothesis":
            mark = annot("hyp", T(lang, "annot_hyp"))
            note = " *(%s)*" % T(lang, "st_hypothesis")
        else:
            mark = annot("read", T(lang, "annot_read"))
            key = "st_" + it["status"]
            note = " *(%s)*" % T(lang, key) if key in I18N[lang] else ""
        out += ["%s**Note %03d · %s**%s" % (mark, k, it["title"], note), "", first_sentence(it["text"], 320), ""]
        if it["kind"] == "question" and it.get("proof"):
            out += ["*%s* %s" % (T(lang, "settle"), first_sentence(it["proof"], 260)), ""]
        link = "%s%s/%s" % (GITHUB_CATALOG, it["binary"], it["file"])
        out += [T(lang, "source") % (it["binary"], it["date"], it["sha"], link), ""]
    if corrections:
        out += ["**%s**" % T(lang, "corr_notes"), ""]
        for c in corrections:
            out += ["%s**%s**" % (annot("corr", T(lang, "annot_corr")), T(lang, "corr_head") % c["date"]), "",
                    "~~%s~~" % c["was"], "", "%s [%s](../../%s)" % (c["now"], c["ref"]["label"], c["ref"]["page"]), ""]
    out += ["</details>", ""]
    return "\n".join(out)


