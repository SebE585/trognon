def load(path):
    with open(path) as f:
        g = yaml.safe_load(f)
    g["_src"] = Path(path).name
    g.setdefault("lang", "en")
    return g


def headings(md_path):
    """The anchors a docs page offers, computed as MkDocs' toc extension does."""
    ids = set()
    for line in md_path.read_text().splitlines():
        m = re.match(r"^#{1,6}\s+(.*?)\s*#*\s*$", line)
        if m:
            text = re.sub(r"[`*_]", "", m.group(1))
            ids.add(slugify(text, "-"))
    return ids


def first_sentence(text, limit=230):
    t = re.sub(r"\s+", " ", str(text)).strip()
    m = re.search(r"(?<=[a-z0-9\)`])\. ", t)
    if m and m.start() < limit:
        return t[: m.start() + 1]
    return t if len(t) <= limit else t[: limit - 1].rstrip() + "…"


def catalog_entries():
    """{binary: [fiche dicts]} for the approved fiches of the decompilation catalog, each with the binary's analysis date."""
    out = {}
    if not CATALOG.is_dir():
        return out
    for d in sorted(p for p in CATALOG.iterdir() if p.is_dir()):
        date = ""
        cov = d / "tool_coverage.json"
        if cov.is_file():
            date = json.loads(cov.read_text()).get("date", "")
        fiches = []
        for f in sorted(d.glob("*.yaml")):
            y = yaml.safe_load(f.read_text())
            if (y.get("publication") or {}).get("status") != "approved":
                continue
            y["_file"] = f.name
            y["_date"] = date
            fiches.append(y)
        if fiches:
            out[d.name] = fiches
    return out


def fiche_title(y):
    return str(y.get("function_name_assigned") or y.get("function_name_apple") or y["_file"]).strip().strip('"')


def catalog_items():
    """{id: dict} for every claim and open question of the approved fiches."""
    items = {}
    for binary, fiches in catalog_entries().items():
        for y in fiches:
            base = {"binary": binary, "file": y["_file"], "title": fiche_title(y), "sha": str(y.get("binary_sha256", ""))[:12], "date": y["_date"]}
            for c in y.get("claims") or []:
                items[c["id"]] = dict(base, kind="claim", text=c.get("text", ""), status=c.get("status", ""))
            for q in (y.get("review") or {}).get("unresolved") or []:
                items[q["id"]] = dict(base, kind="question", text=q.get("text", ""), proof=q.get("proof_needed", ""))
    return items


