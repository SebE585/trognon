#!/usr/bin/env python3
"""Build and check the guided journey pages from their YAML graph.

    python3 -I tools/journey_build.py            # write docs/<lang>/journey/*.md from docs/journey-src/*.yaml
    python3 -I tools/journey_build.py --check    # validate the graph and fail if the generated pages are stale

The pages are generated, never edited by hand. The checks exist so that the story cannot drift away from the reference
documentation: a choice that leads nowhere, an unreachable page, a link to a page or heading that does not exist, an evidence
bundle that does not exist, or a step tagged DEVICE that names no evidence all stop the build.
"""
import argparse
import re
import sys
from collections import deque
from pathlib import Path

import yaml
from markdown.extensions.toc import slugify

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
EVIDENCE = ROOT / "evidence"
TAGS = {"DEVICE", "SOURCE", "HYPOTHESIS", "EMU", None}
KINDS = {"start", "step", "side", "frontier-hub", "frontier", "grimoire-hub", "grimoire"}
TAG_CLASS = {"DEVICE": "tag-device", "SOURCE": "tag-source", "HYPOTHESIS": "tag-hyp", "EMU": "tag-emu"}
GENERATED = "<!-- generated by tools/journey_build.py from docs/journey-src/{src}: do not edit -->\n"
CATALOG = ROOT / "tools" / "iop_analysis" / "catalog"
GITHUB_CATALOG = "https://github.com/SebE585/trognon/blob/main/tools/iop_analysis/catalog/"


def load(path):
    with open(path) as f:
        g = yaml.safe_load(f)
    g["_src"] = Path(path).name
    return g


def headings(md_path):
    """The anchors a docs page offers, computed as MkDocs' toc extension does."""
    ids = set()
    for line in md_path.read_text().splitlines():
        m = re.match(r"^#{1,6}\s+(.*?)\s*#*\s*$", line)
        if m:
            text = re.sub(r"[`*_]", "", m.group(1))
            ids.add(slugify(text, "-"))
    return ids


def first_sentence(text, limit=230):
    t = re.sub(r"\s+", " ", str(text)).strip()
    m = re.search(r"(?<=[a-z0-9\)`])\. ", t)
    if m and m.start() < limit:
        return t[: m.start() + 1]
    return t if len(t) <= limit else t[: limit - 1].rstrip() + "…"


def catalog_entries():
    """{binary: [fiche dicts]} for the approved fiches of the decompilation catalog."""
    out = {}
    if not CATALOG.is_dir():
        return out
    for d in sorted(p for p in CATALOG.iterdir() if p.is_dir()):
        fiches = []
        for f in sorted(d.glob("*.yaml")):
            y = yaml.safe_load(f.read_text())
            if (y.get("publication") or {}).get("status") != "approved":
                continue
            y["_file"] = f.name
            fiches.append(y)
        if fiches:
            out[d.name] = fiches
    return out


def expand_grimoire(g):
    """Add the generated Grimoire pages (one per decompiled binary) and the choices that lead to them."""
    hub = next((n for n in g["nodes"] if n["kind"] == "grimoire-hub"), None)
    if hub is None:
        return
    entries = catalog_entries()
    blurbs = g.get("grimoire_blurbs", {})
    ids = {b: "grimoire-" + slugify(b, "-") for b in entries}
    for b, fiches in entries.items():
        g["nodes"].append({
            "id": ids[b], "kind": "grimoire", "title": b, "tag": None, "binary": b, "fiches": fiches,
            "blurb": blurbs.get(b, ""),
            "choices": [{"text": "Back to the Grimoire.", "to": hub["id"]}],
        })
        hub.setdefault("choices", []).append({"text": "%s (%d entries)" % (b, len(fiches)), "to": ids[b]})
    hub["choices"].sort(key=lambda c: c["to"] == g["start"])  # the way back comes last
    for n in list(g["nodes"]):
        for b in n.get("grimoire", []):
            if b not in ids:
                raise SystemExit("%s: grimoire binary %r is not in the catalog" % (n["id"], b))
            n.setdefault("choices", []).append({"text": "The kernel's side: %s (the Grimoire)." % b, "to": ids[b]})


def check(g):
    errors = []
    nodes = {}
    for n in g["nodes"]:
        if n["id"] in nodes:
            errors.append("duplicate node id %r" % n["id"])
        nodes[n["id"]] = n
    if g.get("start") not in nodes:
        errors.append("start node %r does not exist" % g.get("start"))
        return errors
    for n in g["nodes"]:
        i = n["id"]
        if n.get("kind") not in KINDS:
            errors.append("%s: unknown kind %r" % (i, n.get("kind")))
        if n.get("tag") not in TAGS:
            errors.append("%s: unknown tag %r" % (i, n.get("tag")))
        for c in n.get("choices", []):
            if c["to"] not in nodes:
                errors.append("%s: choice %r leads to a missing node %r" % (i, c["text"], c["to"]))
        if not n.get("choices"):
            errors.append("%s: dead end (no choice)" % i)
        if n.get("kind") == "grimoire" and not n.get("fiches"):
            errors.append("%s: a Grimoire page with no approved entry" % i)
        if n.get("kind") == "frontier":
            for field in ("know", "guess", "next"):
                if not n.get(field):
                    errors.append("%s: a frontier node needs %r" % (i, field))
            if not n.get("refs"):
                errors.append("%s: a frontier node needs at least one reference page" % i)
        if n.get("tag") == "DEVICE" and not n.get("evidence"):
            errors.append("%s: tagged DEVICE but names no evidence bundle" % i)
        for b in n.get("evidence", []):
            if not (EVIDENCE / b).is_dir():
                errors.append("%s: evidence bundle %r does not exist" % (i, b))
        for r in n.get("refs", []):
            page, _, anchor = r["page"].partition("#")
            p = DOCS / page
            if not p.is_file():
                errors.append("%s: reference page %r does not exist" % (i, page))
            elif anchor and anchor not in headings(p):
                errors.append("%s: reference %r has no heading %r" % (i, page, anchor))
        fig = n.get("figure")
        if fig and not (DOCS / fig["src"]).is_file():
            errors.append("%s: figure %r does not exist" % (i, fig["src"]))
    seen = {g["start"]}
    q = deque([g["start"]])
    while q:
        for c in nodes[q.popleft()].get("choices", []):
            if c["to"] in nodes and c["to"] not in seen:
                seen.add(c["to"])
                q.append(c["to"])
    for i in nodes:
        if i not in seen:
            errors.append("%s: not reachable from the start" % i)
    return errors


def routes(g):
    """Shortest route from the start to each node, over the choices (a stable breadcrumb)."""
    nodes = {n["id"]: n for n in g["nodes"]}
    parent = {g["start"]: None}
    q = deque([g["start"]])
    while q:
        cur = q.popleft()
        if nodes[cur].get("kind") == "side":
            continue  # a side branch is never part of the main trail
        for c in nodes[cur].get("choices", []):
            if c["to"] in nodes and c["to"] not in parent:
                parent[c["to"]] = cur
                q.append(c["to"])
    out = {}
    for i in nodes:
        path, cur = [], i
        while cur is not None:
            path.append(cur)
            cur = parent.get(cur)
        out[i] = list(reversed(path))
    return out


def tag_html(tag):
    return '<span class="tag %s">%s</span>' % (TAG_CLASS[tag], tag) if tag else ""


def grimoire_body(n):
    out = []
    if n.get("blurb"):
        out += [n["blurb"], ""]
    out += ["Each entry is a function or a table read in the decompiled binary. It records what was read, with its status; no Apple code is stored here.", ""]
    for y in n["fiches"]:
        review = y.get("review") or {}
        claims = y.get("claims") or []
        open_q = review.get("unresolved") or []
        title = str(y.get("function_name_assigned") or y.get("function_name_apple") or y["_file"]).strip().strip('"')
        addr = y.get("entry_code_address")
        out += ["## %s" % title, ""]
        meta = "Review: %s · %d claim%s · %d open question%s" % (
            review.get("status", "unknown"), len(claims), "" if len(claims) == 1 else "s", len(open_q), "" if len(open_q) == 1 else "s")
        if addr:
            meta = "Entry `%s` · " % addr + meta
        out += [meta, ""]
        for c in claims:
            out.append("- **%s** (%s): %s" % (c.get("id", "?"), str(c.get("status", "?")).replace("_", " "), first_sentence(c.get("text", ""))))
        if claims:
            out.append("")
        for q in open_q:
            out.append("- *Open* **%s**: %s" % (q.get("id", "?"), first_sentence(q.get("text", ""))))
        if open_q:
            out.append("")
        out += ["[Full entry](%s%s/%s)" % (GITHUB_CATALOG, n["binary"], y["_file"]), ""]
    return "\n".join(out)


def page_for(g, n, route, nodes):
    lines = ["---", "title: %s" % n["title"], "hide:", "  - navigation", "  - toc", "---", "", GENERATED.format(src=g["_src"])]
    trail = " → ".join(
        ("[%s](%s.md)" % (nodes[i]["title"], i)) if i != n["id"] else "**%s**" % nodes[i]["title"] for i in route
    )
    lines += ['<div class="journey-trail" markdown>', "You are exploring: " + trail, "</div>", ""]
    lines += ["# %s" % n["title"], ""]
    if n.get("tag"):
        lines += ["How sure we are: %s" % tag_html(n["tag"]), ""]
    if n["kind"] == "grimoire":
        lines += [grimoire_body(n), ""]
    elif n["kind"] == "frontier":
        for label, key in (("What we know", "know"), ("What we guess", "guess"), ("What would settle it", "next")):
            lines += ["## " + label, "", n[key].strip(), ""]
        if n.get("tag"):
            lines += ["*This describes an experiment, not a procedure to follow: a step that writes to the phone's hardware is only run after a written description and an explicit decision.*", ""]
    else:
        lines += [n["text"].strip(), ""]
    fig = n.get("figure")
    if fig:
        lines += ["![%s](../../%s)" % (fig["alt"], fig["src"]), "", "*%s*" % fig["caption"], ""]
    lines += ["## Where to next?", "", '<div class="journey-choices" markdown>', ""]
    for c in n["choices"]:
        lines.append("- [%s](%s.md)" % (c["text"], c["to"]))
    lines += ["", "</div>", ""]
    foot = []
    if n.get("refs"):
        foot.append("**Go deeper in the reference:** " + " · ".join("[%s](../../%s)" % (r["label"], r["page"]) for r in n["refs"]))
    if n.get("evidence"):
        foot.append("**Evidence:** " + " · ".join("[`%s`](https://github.com/SebE585/trognon/tree/main/evidence/%s)" % (b, b) for b in n["evidence"]))
    prev = route[-2] if len(route) > 1 else None
    nav = []
    if prev:
        nav.append("[← Previous step](%s.md)" % prev)
    nav += ["[Map of the journey](index.md)", "[Reference manual](../README.md)"]
    foot.append(" · ".join(nav))
    lines += ["\n\n".join(foot), ""]
    return "\n".join(lines)


def index_page(g, rts, nodes):
    lines = ["---", "title: %s" % g["title"], "hide:", "  - navigation", "  - toc", "---", "", GENERATED.format(src=g["_src"])]
    lines += ["# %s" % g["title"], "",
              "A guided path through what Trognon has observed on a real iPhone 3GS. Two or three choices at each step, an honest "
              "statement of how sure we are, and at the end the places where our knowledge stops. "
              "If you already know what you want, go straight to the [reference manual](../README.md) or the [search](../../research/index.md).", ""]
    lines += ["[Start the journey](%s.md){ .md-button .md-button--primary }" % g["start"], ""]
    lines += ["## Map of the journey", "", "| Step | How sure | Reached by |", "|---|---|---|"]
    for n in g["nodes"]:
        by = " → ".join(nodes[i]["title"] for i in rts[n["id"]][:-1]) or "the start"
        lines.append("| [%s](%s.md) | %s | %s |" % (n["title"], n["id"], tag_html(n.get("tag")) or "—", by))
    lines.append("")
    return "\n".join(lines)


def render(g):
    nodes = {n["id"]: n for n in g["nodes"]}
    rts = routes(g)
    out = {"index.md": index_page(g, rts, nodes)}
    for n in g["nodes"]:
        out[n["id"] + ".md"] = page_for(g, n, rts[n["id"]], nodes)
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="validate and compare with the files on disk, write nothing")
    args = ap.parse_args(argv)
    status = 0
    for src in sorted((DOCS / "journey-src").glob("*.yaml")):
        g = load(src)
        expand_grimoire(g)
        errors = check(g)
        if errors:
            print("%s:" % src.name)
            for e in errors:
                print("  " + e)
            status = 1
            continue
        target = DOCS / g.get("lang", "en") / "journey"
        pages = render(g)
        if args.check:
            for name, text in pages.items():
                f = target / name
                if not f.is_file() or f.read_text() != text:
                    print("%s: %s is missing or stale (run make journey)" % (src.name, f.relative_to(ROOT)))
                    status = 1
            extra = {p.name for p in target.glob("*.md")} - set(pages) if target.is_dir() else set()
            for name in sorted(extra):
                print("%s: %s is not in the graph (remove it)" % (src.name, (target / name).relative_to(ROOT)))
                status = 1
        else:
            target.mkdir(parents=True, exist_ok=True)
            for name, text in pages.items():
                (target / name).write_text(text)
            print("%s: %d pages written to %s" % (src.name, len(pages), target.relative_to(ROOT)))
    if args.check and status == 0:
        print("journey: graph valid, generated pages up to date")
    return status


if __name__ == "__main__":
    sys.exit(main())
