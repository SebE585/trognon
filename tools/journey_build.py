def review_class(status):
    return {"complete": "kmap-complete", "partial": "kmap-partial"}.get(status, "kmap-none")


def counts(fiches):
    claims = sum(len(y.get("claims") or []) for y in fiches)
    opens = sum(len((y.get("review") or {}).get("unresolved") or []) for y in fiches)
    return claims, opens


def knowledge_map(lang, entries, ids):
    """A map of what the decompilation has covered: one tile per entry, coloured by review state, numbered by open questions."""
    out = ["## %s" % T(lang, "km_title"), "", T(lang, "km_intro"), "", T(lang, "km_legend"), "", '<div class="kmap" markdown="1">', ""]
    tot = [0, 0, 0]
    for b, fiches in entries.items():
        claims, opens = counts(fiches)
        tot[0] += len(fiches)
        tot[1] += claims
        tot[2] += opens
        ent = ("y", "ies") if lang == "en" else ("", "s")
        args = (b, len(fiches), plural(len(fiches), *ent), claims, plural(claims), opens, plural(opens))
        if lang == "fr":
            args += (plural(opens),)  # "questions ouvertes": the adjective agrees too
        out += [T(lang, "km_row") % args, ""]
        tiles = []
        for y in fiches:
            q = len((y.get("review") or {}).get("unresolved") or [])
            status = (y.get("review") or {}).get("status")
            word = T(lang, {"complete": "rv_complete", "partial": "rv_partial"}.get(status, "rv_none"))
            symbol = {"complete": "✓", "partial": "◐"}.get(status, "○")
            title = fiche_title(y).replace('"', "'").replace("*", "&#42;").replace("_", "&#95;")  # markdown-safe attribute
            label = "%s, %s, %d %s" % (title, word, q, T(lang, "q_open"))
            tiles.append('[%s%d](%s.md){ .kmap-tile .%s title="%s" aria-label="%s" }' % (symbol, q, ids[b], review_class(status), label, label))
        out += [" ".join(tiles), ""]
    out += ["</div>", "", T(lang, "km_total") % tuple(tot), ""]
    return "\n".join(out)


def grimoire_body(n, lang):
    out = []
    if n.get("blurb"):
        out += [n["blurb"], ""]
    out += [T(lang, "g_intro"), ""]
    for y in n["fiches"]:
        review = y.get("review") or {}
        claims = y.get("claims") or []
        open_q = review.get("unresolved") or []
        out += ["## %s" % fiche_title(y), ""]
        state = review.get("status", "unknown")
        if lang == "fr":
            state = {"complete": "complète", "partial": "partielle", "not_reviewed": "non relue", "unknown": "inconnue"}.get(state, state)
        if lang == "en":
            meta = T(lang, "g_meta") % (state, len(claims), plural(len(claims)), len(open_q), plural(len(open_q)))
        else:
            meta = T(lang, "g_meta") % (state, len(claims), plural(len(claims)), len(open_q), plural(len(open_q)), plural(len(open_q)))
        if y.get("entry_code_address"):
            meta = T(lang, "g_entry") % y["entry_code_address"] + meta
        out += [meta, ""]
        for c in claims:
            out.append("- **%s** (%s): %s" % (c.get("id", "?"), str(c.get("status", "?")).replace("_", " "), first_sentence(c.get("text", ""))))
        if claims:
            out.append("")
        for q in open_q:
            out.append("- *%s* **%s**: %s" % (T(lang, "g_open"), q.get("id", "?"), first_sentence(q.get("text", ""))))
        if open_q:
            out.append("")
        out += ["[%s](%s%s/%s)" % (T(lang, "g_full"), GITHUB_CATALOG, n["binary"], y["_file"]), ""]
    framed = missions_by_question()
    mine = [(q["id"], framed[q["id"]]) for y in n["fiches"] for q in (y.get("review") or {}).get("unresolved") or [] if q["id"] in framed]
    if mine:
        page = "../missions.md" if lang == "en" else "../../en/missions.md"
        out += ["## %s" % T(lang, "g_missions_head"), ""]
        out += ["- %s (`%s`, %s)" % (title, qid, state) for qid, (title, state) in mine]
        out += ["", "[%s](%s)" % (T(lang, "g_missions_all"), page), ""]
    return "\n".join(out)


def expand_grimoire(g):
    """Add the generated Grimoire pages (one per decompiled binary) and the choices that lead to them."""
    lang = g["lang"]
    hub = next((n for n in g["nodes"] if n["kind"] == "grimoire-hub"), None)
    if hub is None:
        return
    entries = catalog_entries()
    blurbs = g.get("grimoire_blurbs", {})
    ids = {b: "grimoire-" + slugify(b, "-") for b in entries}
    hub["_entries"], hub["_ids"] = entries, ids
    for b, fiches in entries.items():
        g["nodes"].append({
            "id": ids[b], "kind": "grimoire", "title": b, "tag": None, "binary": b, "fiches": fiches,
            "blurb": blurbs.get(b, ""),
            "choices": [{"text": T(lang, "back_grimoire"), "to": hub["id"]}],
        })
        hub.setdefault("choices", []).append({"text": "%s (%d)" % (b, len(fiches)), "to": ids[b]})
    hub["choices"].sort(key=lambda c: c["to"] == g["start"])  # the way back comes last
    for n in list(g["nodes"]):
        for b in n.get("grimoire", []):
            if b not in ids:
                raise SystemExit("%s: grimoire binary %r is not in the catalog" % (n["id"], b))
            n.setdefault("choices", []).append({"text": T(lang, "kernel_side") % b, "to": ids[b]})


# ---- checks ------------------------------------------------------------------------------------------------------------
def check(g):
    errors = []
    nodes = {}
    for n in g["nodes"]:
        if n["id"] in nodes:
            errors.append("duplicate node id %r" % n["id"])
        nodes[n["id"]] = n
    if g.get("start") not in nodes:
        errors.append("start node %r does not exist" % g.get("start"))
        return errors
    if g.get("lang", "en") not in I18N:
        errors.append("unknown language %r" % g.get("lang"))
    for n in g["nodes"]:
        i = n["id"]
        if n.get("kind") not in KINDS:
            errors.append("%s: unknown kind %r" % (i, n.get("kind")))
        if n.get("tag") not in TAGS:
            errors.append("%s: unknown tag %r" % (i, n.get("tag")))
        for c in n.get("choices", []):
            if c["to"] not in nodes:
                errors.append("%s: choice %r leads to a missing node %r" % (i, c["text"], c["to"]))
        if not n.get("choices"):
            errors.append("%s: dead end (no choice)" % i)
        if n.get("kind") == "grimoire" and not n.get("fiches"):
            errors.append("%s: a Grimoire page with no approved entry" % i)
        if n.get("kind") == "frontier":
            for field in ("know", "guess", "next"):
                if not n.get(field):
                    errors.append("%s: a frontier node needs %r" % (i, field))
            if not n.get("refs"):
                errors.append("%s: a frontier node needs at least one reference page" % i)
        if n.get("tag") == "DEVICE" and not n.get("evidence"):
            errors.append("%s: tagged DEVICE but names no evidence bundle" % i)
        for b in n.get("evidence", []):
            if not (EVIDENCE / b).is_dir():
                errors.append("%s: evidence bundle %r does not exist" % (i, b))
        refs = list(n.get("refs", [])) + [c["ref"] for c in n.get("corrections", [])]
        for r in refs:
            page, _, anchor = r["page"].partition("#")
            p = DOCS / page
            if not p.is_file():
                errors.append("%s: reference page %r does not exist" % (i, page))
            elif anchor and anchor not in headings(p):
                errors.append("%s: reference %r has no heading %r" % (i, page, anchor))
        for c in n.get("corrections", []):
            if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(c.get("date", ""))):
                errors.append("%s: a correction needs an ISO date" % i)
            for field in ("was", "now"):
                if not c.get(field):
                    errors.append("%s: a correction needs %r" % (i, field))
        if n.get("visual") and n["visual"] not in VISUAL_STATES:
            errors.append("%s: unknown visual %r" % (i, n["visual"]))
        for nid in n.get("notebook", []):
            if nid not in ITEMS:
                errors.append("%s: notebook note %r is not in the approved catalog" % (i, nid))
        fig = n.get("figure")
        if fig and not (DOCS / fig["src"]).is_file():
            errors.append("%s: figure %r does not exist" % (i, fig["src"]))
    seen = {g["start"]}
    q = deque([g["start"]])
    while q:
        for c in nodes[q.popleft()].get("choices", []):
            if c["to"] in nodes and c["to"] not in seen:
                seen.add(c["to"])
                q.append(c["to"])
    for i in nodes:
        if i not in seen:
            errors.append("%s: not reachable from the start" % i)
    return errors


def check_pages(pages):
    """Every generated page must start with valid YAML front matter (an unquoted colon in a title once broke four pages)."""
    errors = []
    for name, text in pages.items():
        m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
        try:
            meta = yaml.safe_load(m.group(1)) if m else None
        except yaml.YAMLError as e:
            errors.append("%s: front matter is not valid YAML (%s)" % (name, str(e).splitlines()[0]))
            continue
        if not isinstance(meta, dict) or not isinstance(meta.get("title"), str):
            errors.append("%s: front matter has no string title" % name)
    return errors


def structure(g):
    """What must be identical between a graph and its translation."""
    out = {}
    for n in g["nodes"]:
        out[n["id"]] = (n.get("kind"), n.get("tag"), [c["to"] for c in n.get("choices", [])], n.get("visual"),
                        tuple(n.get("evidence", [])), tuple(n.get("notebook", [])), tuple(n.get("grimoire", [])),
                        len(n.get("corrections", [])), len(n.get("refs", [])))
    return (g.get("start"), out)


def parity(graphs):
    """Every translation must have the structure of the English graph with the same stem."""
    errors = []
    by_stem = {}
    for g in graphs:
        by_stem.setdefault(g["_src"].replace(".fr.yaml", ".yaml"), {})[g["lang"]] = g
    for stem, langs in by_stem.items():
        base = langs.get("en")
        if base is None:
            errors.append("%s: no English graph to translate from" % stem)
            continue
        for lang, g in langs.items():
            if lang == "en":
                continue
            a, b = structure(base), structure(g)
            if a[0] != b[0]:
                errors.append("%s (%s): the start node differs from the English graph" % (stem, lang))
            for i in sorted(set(a[1]) | set(b[1])):
                if a[1].get(i) != b[1].get(i):
                    errors.append("%s (%s): node %r differs in structure from the English graph" % (stem, lang, i))
    return errors


def routes(g):
    """Shortest route from the start to each node, over the choices (a stable breadcrumb)."""
    nodes = {n["id"]: n for n in g["nodes"]}
    parent = {g["start"]: None}
    q = deque([g["start"]])
    while q:
        cur = q.popleft()
        if nodes[cur].get("kind") == "side":
            continue  # a side branch is never part of the main trail
        for c in nodes[cur].get("choices", []):
            if c["to"] in nodes and c["to"] not in parent:
                parent[c["to"]] = cur
                q.append(c["to"])
    out = {}
    for i in nodes:
        path, cur = [], i
        while cur is not None:
            path.append(cur)
            cur = parent.get(cur)
        out[i] = list(reversed(path))
    return out


# ---- rendering ---------------------------------------------------------------------------------------------------------
def tag_html(tag):
    return '<span class="tag %s">%s</span>' % (TAG_CLASS[tag], tag) if tag else ""


def front_matter(title, src):
    return ["---", "title: %s" % json.dumps(title), "source: docs/journey-src/%s" % src, "hide:", "  - navigation", "  - toc", "  - footer", "---", "", GENERATED.format(src=src)]


def page_for(g, n, route, nodes):
    lang = g["lang"]
    lines = front_matter(n["title"], g["_src"])
    trail = " → ".join(("[%s](%s.md)" % (nodes[i]["title"], i)) if i != n["id"] else "**%s**" % nodes[i]["title"] for i in route)
    lines += ['<div class="journey-trail" markdown>', T(lang, "exploring") + trail, "</div>", ""]
    lines += ["# %s" % n["title"], ""]
    if n.get("visual"):
        cap = VISUAL_CAPTIONS[lang][n["visual"]]
        # Decorative alt text: the caption right under the picture says the same thing, and a reader should not hear it twice.
        lines += ['<figure class="journey-figure" markdown="1">', "![](../../%s){ .journey-visual }" % visual_rel(lang, n["visual"]),
                  "<figcaption>%s</figcaption>" % cap, "</figure>", ""]
    if n.get("tag"):
        lines += [T(lang, "how_sure") + tag_html(n["tag"]), ""]
    if n["kind"] == "grimoire":
        lines += [grimoire_body(n, lang), ""]
    elif n["kind"] == "frontier":
        for key, label in (("know", "k_know"), ("guess", "k_guess"), ("next", "k_next")):
            lines += ["## " + T(lang, label), "", n[key].strip(), ""]
        if n.get("tag"):
            lines += [T(lang, "experiment"), ""]
    else:
        lines += [n["text"].strip(), ""]
    if n["kind"] == "grimoire-hub":
        lines += [T(lang, "g_missions_hub"), "", knowledge_map(lang, n["_entries"], n["_ids"]), ""]
    fig = n.get("figure")
    if fig:
        lines += ["![%s](../../%s)" % (fig["alt"], fig["src"]), "", "*%s*" % fig["caption"], ""]
    lines += ["## " + T(lang, "next"), "", '<div class="journey-choices" markdown>', ""]
    for c in n["choices"]:
        hint = '<span class="journey-hint">%s</span>' % c["hint"] if c.get("hint") else ""
        lines.append("- [%s%s](%s.md)" % (c["text"], hint, c["to"]))
    lines += ["", "</div>", ""]
    nb = notebook_block(n, lang)
    if nb:
        lines += [nb]
    more = []
    if n.get("refs"):
        more.append(T(lang, "deeper") + " · ".join("[%s](../../%s)" % (r["label"], r["page"]) for r in n["refs"]))
    if n.get("evidence"):
        more.append(T(lang, "evidence") + " · ".join("[`%s`](%s%s)" % (b, GITHUB_EVIDENCE, b) for b in n["evidence"]))
    if more:
        lines += ['<details class="journey-more" markdown="1">', "<summary>%s</summary>" % T(lang, "proof_ref"), "", "\n\n".join(more), "", "</details>", ""]
    prev = route[-2] if len(route) > 1 else None
    nav = []
    if prev:
        nav.append("[%s](%s.md)" % (T(lang, "prev"), prev))
    nav += ["[%s](index.md)" % T(lang, "map"), "[%s](../README.md)" % T(lang, "manual")]
    lines += ['<p class="journey-nav" markdown="1">' + " · ".join(nav) + "</p>", ""]
    return "\n".join(lines)


def index_page(g, rts, nodes):
    lang = g["lang"]
    lines = front_matter(g["title"], g["_src"])
    lines += ["# %s" % g["title"], "", T(lang, "idx_intro"), "",
              "[%s](%s.md){ .md-button .md-button--primary }" % (T(lang, "start_button"), g["start"]), "",
              "## " + T(lang, "idx_map"), "", "| %s | %s | %s |" % T(lang, "map_cols"), "|---|---|---|"]
    for n in g["nodes"]:
        by = " → ".join(nodes[i]["title"] for i in rts[n["id"]][:-1]) or T(lang, "map_start")
        lines.append("| [%s](%s.md) | %s | %s |" % (n["title"], n["id"], tag_html(n.get("tag")) or "—", by))
    lines.append("")
    return "\n".join(lines)


def render(g):
    nodes = {n["id"]: n for n in g["nodes"]}
    rts = routes(g)
    out = {"index.md": index_page(g, rts, nodes)}
    for n in g["nodes"]:
        out[n["id"] + ".md"] = page_for(g, n, rts[n["id"]], nodes)
    return out


def assets(g):
    """{path relative to docs: text} for the generated visuals this graph uses."""
    used = {n["visual"] for n in g["nodes"] if n.get("visual")}
    return {visual_rel(g["lang"], v): phone_svg(v, g["lang"]) for v in sorted(used)}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="validate and compare with the files on disk, write nothing")
    args = ap.parse_args(argv)
    status = 0
    ITEMS.clear()
    ITEMS.update(catalog_items())
    graphs = []
    for src in sorted((DOCS / "journey-src").glob("*.yaml")):
        g = load(src)
        expand_grimoire(g)
        errors = check(g)
        if not errors:
            errors = check_pages(render(g))
        if errors:
            print("%s:" % src.name)
            for e in errors:
                print("  " + e)
            status = 1
            continue
        graphs.append(g)
    errors = parity(graphs)
    if errors:
        for e in errors:
            print(e)
        status = 1
    if status:
        return status
    for g in graphs:
        target = DOCS / g["lang"] / "journey"
        pages, files = render(g), assets(g)
        if args.check:
            for name, text in pages.items():
                f = target / name
                if not f.is_file() or f.read_text() != text:
                    print("%s: %s is missing or stale (run make journey)" % (g["_src"], f.relative_to(ROOT)))
                    status = 1
            for rel, text in files.items():
                f = DOCS / rel
                if not f.is_file() or f.read_text() != text:
                    print("%s: %s is missing or stale (run make journey)" % (g["_src"], f.relative_to(ROOT)))
                    status = 1
            for name in sorted({p.name for p in target.glob("*.md")} - set(pages) if target.is_dir() else set()):
                print("%s: %s is not in the graph (remove it)" % (g["_src"], (target / name).relative_to(ROOT)))
                status = 1
        else:
            target.mkdir(parents=True, exist_ok=True)
            for name, text in pages.items():
                (target / name).write_text(text)
            for rel, text in files.items():
                (DOCS / rel).parent.mkdir(parents=True, exist_ok=True)
                (DOCS / rel).write_text(text)
            print("%s: %d pages and %d visuals written to %s" % (g["_src"], len(pages), len(files), target.relative_to(ROOT)))
    if args.check and status == 0:
        print("journey: graphs valid, translations in step, generated files up to date")
    return status


if __name__ == "__main__":
    sys.exit(main())
